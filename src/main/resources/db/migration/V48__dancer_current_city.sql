-- V48: 舞伴「当前所在城市」（2026-08-26）——
-- qwt_dancers.current_city（从已选常驻城市 cities 中再选中一个作为当前所在城市）
--
-- 背景：舞伴可常驻/活跃于最多 3 个城市（qwt_dancer_cities），用户在「解锁联系方式-
-- 是否同城」时需判断自己与舞伴是否同城——仅凭「城市列表」无法表达舞伴<b>当前</b>
-- 所在城市。新增 current_city：管理员在 dancer-edit 从已选城市中单选（多城市时
-- 显式指定，单城市时即该城市本身）。
--
-- 规则：
-- 1. current_city（varchar(50) NULL）——必须为已选常驻城市之一（服务层校验，
--    非法值 1001「当前所在城市须为常驻城市之一」）；未填城市（纯线上舞伴）
--    恒为 NULL；存量舞伴为 NULL（前端回退主城市展示，无需数据迁移）。
-- 2. 城市全量覆盖语义：编辑 cities 时若 current_city 不在新列表中 → 服务层
--    回退新主城市（不报错，防脏数据）；显式传入不在列表中的值 → 1001。
-- 3. 枚举列禁 CHECK 约束（项目约定：自由文本列不设 CHECK，应用层校验）。
-- ============================================================================

ALTER TABLE qwt_dancers
    ADD COLUMN current_city varchar(50);
