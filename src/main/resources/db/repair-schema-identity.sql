-- ============================================================================
-- repair-schema-identity.sql — 修复 2026-08-04 迁移事故丢失的 IDENTITY / 主键 / NOT NULL
--
-- 事故根因：DB 迁近区时用 DataGrip「全选表 → 拖拽到目标库」方式迁移。
-- DataGrip 跨库复制按普通列类型重建表结构：索引与唯一约束保留了，
-- 但 IDENTITY（及序列）、主键、NOT NULL、列默认值全部丢失——9 张 qwt_* 表
-- 的 id 列全部退化为可空 bigint。后果：
--   ① 一切需要回读生成主键的写入（JPA IDENTITY insert）抛
--      AssertionFailure: null identifier（编辑场所改状态即此路径）；
--   ② 不回读主键的写入（view upsert）静默写入 id=NULL 的脏行。
-- Hibernate 的 ddl-auto: validate 不校验主键/identity/NOT NULL，故启动期无告警。
--
-- 本脚本修复内容（全部幂等，可重复执行；对健康库执行无副作用）：
--   1. 回填已存在的 id=NULL 脏行（事故期间 qwt_venue_views 的浏览记录）
--   2. 为所有表重建 PRIMARY KEY (id)（隐含 id NOT NULL）
--   3. id 列 ADD GENERATED BY DEFAULT AS IDENTITY（与 Hibernate 建库 DDL 一致）
--   4. 序列定位到 max(id)（数据迁移带显式 id，必须重置序列避免主键冲突）
--   5. 恢复实体契约的 NOT NULL 约束（执行前先校验无违例行，有则中止）
--   6. 恢复列默认值（qwt_venues.status='OPEN' / sort_weight=0）
--
-- 执行方式：Supabase SQL Editor 或 psql 直接整段执行（单个 DO 块）。
-- 执行后启动一次服务，SchemaIntegrityChecker 会复核（见 AGENTS.md「Schema 完整性」）。
-- ============================================================================

DO $$
DECLARE
    rec        record;
    col        text;
    v_nulls    bigint;
    v_max      bigint;
BEGIN
    FOR rec IN
        SELECT v.tbl, v.nn_cols
        FROM (VALUES
            -- 表名 + 实体契约中 nullable=false 的业务列（BaseEntity.deleted 一并列出；
            -- qwt_venue_status_logs / qwt_venue_views 不含 BaseEntity 字段）
            ('qwt_users',               ARRAY['open_id', 'role', 'deleted']),
            ('qwt_venues',              ARRAY['name', 'status', 'city', 'district', 'sort_weight', 'deleted']),
            ('qwt_favorites',           ARRAY['user_id', 'venue_id', 'deleted']),
            ('qwt_venue_posts',         ARRAY['venue_id', 'title', 'content', 'publisher_type', 'deleted']),
            ('qwt_venue_feedbacks',     ARRAY['venue_id', 'user_id', 'type', 'handled', 'deleted']),
            ('qwt_venue_status_logs',   ARRAY['venue_id', 'to_status']),
            ('qwt_venue_status_reports',ARRAY['venue_id', 'user_id', 'reason', 'deleted']),
            ('qwt_tag_interactions',    ARRAY['user_id', 'venue_id', 'tag', 'liked', 'deleted']),
            ('qwt_venue_views',         ARRAY['venue_id', 'view_date'])
        ) AS v(tbl, nn_cols)
    LOOP
        -- 0) 前置校验：NOT NULL 违例行存在则中止（防脚本在脏数据上盲目加约束）
        FOREACH col IN ARRAY rec.nn_cols
        LOOP
            EXECUTE format('SELECT count(*) FROM %I WHERE %I IS NULL', rec.tbl, col) INTO v_nulls;
            IF v_nulls > 0 THEN
                RAISE EXCEPTION '[%] 存在 % 行 % 为 NULL，无法安全添加 NOT NULL，请先人工处理',
                    rec.tbl, v_nulls, col;
            END IF;
        END LOOP;

        -- 1) 回填 id=NULL 脏行（事故期间写入的浏览记录等），按 max(id)+1 起编号
        EXECUTE format('SELECT count(*) FROM %I WHERE id IS NULL', rec.tbl) INTO v_nulls;
        IF v_nulls > 0 THEN
            EXECUTE format('SELECT COALESCE(max(id), 0) FROM %I', rec.tbl) INTO v_max;
            EXECUTE format(
                'WITH numbered AS ('
                '  SELECT ctid AS rid, %s + ROW_NUMBER() OVER (ORDER BY ctid) AS new_id'
                '  FROM %I WHERE id IS NULL'
                ') '
                'UPDATE %I t SET id = n.new_id FROM numbered n WHERE t.ctid = n.rid',
                v_max, rec.tbl, rec.tbl);
            RAISE NOTICE '[%] 回填 % 行 NULL id（自 % 起）', rec.tbl, v_nulls, v_max + 1;
        END IF;

        -- 2) 重建主键（隐含 id NOT NULL）；约束名沿用 PG 默认 <表名>_pkey
        IF NOT EXISTS (
            SELECT 1 FROM pg_constraint c
            WHERE c.conrelid = rec.tbl::regclass AND c.contype = 'p'
        ) THEN
            EXECUTE format('ALTER TABLE %I ADD PRIMARY KEY (id)', rec.tbl);
            RAISE NOTICE '[%] 重建 PRIMARY KEY (id)', rec.tbl;
        END IF;

        -- 3) id 恢复 IDENTITY（与 Hibernate PostgreSQL 建表 DDL 一致：generated by default）
        IF NOT EXISTS (
            SELECT 1
            FROM pg_class c
            JOIN pg_attribute a ON a.attrelid = c.oid
            WHERE c.oid = rec.tbl::regclass AND a.attname = 'id' AND a.attidentity <> ''
        ) THEN
            EXECUTE format('ALTER TABLE %I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', rec.tbl);
            RAISE NOTICE '[%] id 恢复 IDENTITY', rec.tbl;
        END IF;

        -- 4) 序列定位到 max(id)：迁移数据带显式 id，序列必须越过已用区间，
        --    否则下一次插入即主键冲突。setval(seq, max, true) → 下次 nextval = max+1
        EXECUTE format('SELECT max(id) FROM %I', rec.tbl) INTO v_max;
        IF v_max IS NOT NULL THEN
            EXECUTE format('SELECT setval(pg_get_serial_sequence(%L, ''id''), %s, true)', rec.tbl, v_max);
        ELSE
            EXECUTE format('SELECT setval(pg_get_serial_sequence(%L, ''id''), 1, false)', rec.tbl);
        END IF;
        RAISE NOTICE '[%] 序列定位完成（max(id)=%）', rec.tbl, COALESCE(v_max::text, '<空表>');

        -- 5) 恢复业务列 NOT NULL（实体 @Column(nullable=false) 契约）
        FOREACH col IN ARRAY rec.nn_cols
        LOOP
            IF EXISTS (
                SELECT 1 FROM information_schema.columns
                WHERE table_schema = 'public' AND table_name = rec.tbl
                  AND column_name = col AND is_nullable = 'YES'
            ) THEN
                EXECUTE format('ALTER TABLE %I ALTER COLUMN %I SET NOT NULL', rec.tbl, col);
                RAISE NOTICE '[%] % 恢复 NOT NULL', rec.tbl, col;
            END IF;
        END LOOP;
    END LOOP;

    -- 6) 恢复列默认值（实体 columnDefinition 契约：status default 'OPEN'、sort_weight default 0）
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'qwt_venues'
          AND column_name = 'status' AND column_default IS NOT NULL
    ) THEN
        ALTER TABLE qwt_venues ALTER COLUMN status SET DEFAULT 'OPEN';
        RAISE NOTICE '[qwt_venues] status 恢复 DEFAULT ''OPEN''';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'qwt_venues'
          AND column_name = 'sort_weight' AND column_default IS NOT NULL
    ) THEN
        ALTER TABLE qwt_venues ALTER COLUMN sort_weight SET DEFAULT 0;
        RAISE NOTICE '[qwt_venues] sort_weight 恢复 DEFAULT 0';
    END IF;

    RAISE NOTICE 'Schema 修复完成：IDENTITY / 主键 / NOT NULL / 序列起点已恢复';
END $$;
