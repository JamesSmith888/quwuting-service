-- V39（MySQL 轨道 = db/migration-mysql）: 到访**次数**列（同自然日去重）
--      （2026-10-06，后端权威文档 = docs/agents/52-venue-presence.md）
--
-- ⚠️ 编号说明：PG 遗留轨道（db/migration）与 MySQL 轨道编号各自独立、勿混用。
--    MySQL 轨道 V38（qwt_venue_visit_metrics）已落库 ⇒ 本迁移为增量 ALTER。
--
-- ── 需求 ────────────────────────────────────────────────────────────────────
--
-- 列表卡片到店足迹行要同时说清两个数字：**N 位舞友 · N 次真实到店足迹**。
-- V38 只落了「人数」（visit_users_30d），没有「次数」⇒ 本迁移补这一列。
--
-- ── 「次」的口径（2026-10-06 用户定案，**自然日去重**） ──────────────────────
--
--   次数 = COUNT(DISTINCT (用户, 门店, 自然日))
--
--   · 用户某天到某店，当天记 1 次（**一天内去多次只记 1 次**）；
--   · 用户连去 3 天，记 3 次；
--   · 用户同一天去了两家不同门店，两家各记 1 次（去重键含 venue_id）。
--
-- ⛔ **不是 ping 条数**：ping 表按 15 分钟写幂等桶（UNIQUE(user,venue,bucket)），
--    一次到店会产生多条 ping（onShow 抖动 / 前台每 15 分钟补采）⇒ 直接 COUNT(*)
--    会把"一次到店"数成 5~6 次。V38 的人数口径用 MAX(createdAt) 时间窗去重，
--    同样无法给出"天"粒度 ⇒ 次数必须**单独取数**（见 VenuePresencePingRepository
--    新增的按日聚合查询），不存在"从人数推次数"的廉价算法。
--
-- ⚠️ **与人数口径的差异是刻意的**（52 号 §4 口径表已登记）：
--    人数 = MAX(createdAt) 时间窗去重（**跨零点连场算 1 次**，舞厅 22:00 进 02:00 出
--    不会被拆成两天）；次数 = 自然日去重（跨零点连场会算 2 次）。
--    两者对"同一次到访"的判断不同，故**必须同源计算、分别落列**，
--    禁止用其中之一推算另一个（推算结果会与真实口径不符）。
--
-- ── 为什么与人数列完全同源（归因 + 分摊 + 排除内部账号） ────────────────────
--
-- 本列若与 visit_users_30d 不同源，会出现"5 位舞友分享 0 次"这类自相矛盾的行：
--  · 归因：同址组共享 / 让渡证据后，某店的证据可能来自**邻居门店的 ping**
--    （现网实证 venue 121：自身 ping = 0，人数 5 全部来自同址邻居）；
--  · 分摊：同址组都在营时按 1/k 分给 k 家（与人数同一分母，避免"次数比人数多出一倍"）；
--  · 排除内部账号：heat.excluded.user.ids（与人数同一集合）。
--
-- ⇒ 由 VenuePresenceService.visitSharesForRanking 在**同一趟归因循环**里算出来，
--    与人数共用 attribution / evidenceVenueIds / share，**不存在第二份归因实现**。
--
-- ── 列设计 ──────────────────────────────────────────────────────────────────
--
--   · decimal(8,2) NOT NULL DEFAULT 0：与人数列同精度（同址分摊产生 1/k 小数）。
--   · 只加 30 天窗口一列：7 天次数无消费方（人数的 7 天列也仅展示），
--     加一列就多一处必须同步的分母（52 号「一个视觉变量只编码一件事」同款纪律）。
--   · 本列**不进热度公式**：次数与人数高度相关（同一份命中集的两个粒度），
--     同时进公式 = 同一信号算两票。公式只读 visit_users_30d（HEAT_BEHAVIOR 不变）。
--   · 时间戳不动：refreshed_at / created_at / updated_at 由刷新任务统一维护。
-- ============================================================================

ALTER TABLE qwt_venue_visit_metrics
    ADD COLUMN visit_events_30d decimal(8,2) NOT NULL DEFAULT 0
        COMMENT '近30天到访次数（(用户,门店,自然日)去重；归因+分摊+排除内部账号，同 visit_users_30d 口径；仅展示，不进公式）'
        AFTER visit_users_7d;