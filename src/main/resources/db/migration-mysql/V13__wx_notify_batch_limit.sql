-- 微信通知「突发批次上限」用户配置（2026-09-08，docs/agents/41-wx-subscribe-notify.md）
--
-- 背景（本次要解决的问题）：微信一次性订阅额度可**无限累加**——调用一次
-- wx.requestSubscribeMessage 且 accept 即 +1，官方无单用户上限；用户若勾选
-- 「总是保持以上选择 + 允许」，后续调用不弹窗静默 +1，可反复点「微信提醒」囤到
-- 几十上百次。叠加发送侧「逐事件逐用户下发、无聚合无频控」的现状，一旦发生
-- 批量状态更新（32 城市 ~992 家门店的批量反转是常态运营动作），关注 N 家的用户
-- 会在同一分钟收到 N 条微信服务通知 → 骚扰 → 用户在设置里关闭订阅消息
-- （微信侧永久、开发者几乎无法拉回）→ 唯一的被动触达通道报废。
--
-- 治理方向（用户 2026-09-08 拍板）：**不限制用户授权（囤额度是有意愿的信号），
-- 改为限制我们自己一次能打断用户几次**——突发窗口内最多发 N 条微信，超出部分
-- 只走站内信（收藏列表角标照常），不扣额度。
--
-- 字段语义（qwt_users.wx_notify_batch_limit）：
--   * 3（默认）= 突发窗口内最多发 3 条微信通知；
--   * 5       = 重度用户档；
--   * 0       = 不限，接收全部门店变动通知（用户自主选择，风险自担）。
-- 前端三档可选（3 / 5 / 不限），默认 3。
--
-- 为什么存用户表而不是 ops-config：这是**用户级偏好**（每人可不同），不是全局开关。
-- 「突发窗口」时长本身是技术参数（识别一批用，不是限流），走配置
-- wechat.subscribe.burst-window-minutes，不入库。
--
-- 幂等：MySQL 无 ADD COLUMN IF NOT EXISTS，Flyway 版本号保证单次执行；
-- 存量用户取默认值 3（DEFAULT 约束覆盖全表，无需回填 UPDATE）。

ALTER TABLE qwt_users
    ADD COLUMN wx_notify_batch_limit tinyint NOT NULL DEFAULT 3 COMMENT '突发窗口内最多下发的微信通知条数（3=默认/5/0=不限）';
