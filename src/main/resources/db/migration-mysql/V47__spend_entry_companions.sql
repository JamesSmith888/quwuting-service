-- ============================================================================
-- V47（MySQL 轨道 = db/migration-mysql）: 计时账目携带「一同计时的人」快照（2026-10-09）
--      （后端权威文档 = docs/agents/40-spend-ledger.md §companions + 54-timer-share.md §十四；
--        前端 = quwuting 仓 docs/agents/44-spend-ledger.md + 59-timer-share.md §十四）
--
-- ── 需求 ────────────────────────────────────────────────────────────────────
-- 经二维码同步的计时（V42 起）结算后，账本流水要能回答「这一笔是和谁一起跳的」：
-- 流水行显示一同计时的人（头像 + 昵称），点开可看详情。
--
-- ── 为什么是「快照列」而不是关联查询 ──────────────────────────────────────────
-- 候选方案 = 账目只存 token，读时去 qwt_timer_shares / qwt_timer_share_joins 联查。否决：
--   ① 账本是「本地为源、云端为镜」（44 号）——本地账目行必须自带展示所需的一切，联查意味着
--      每条流水一次网络往返（账本页要渲染几十行），弱网下（舞厅地下室）退化成空白；
--   ② token 是 bearer 凭据（V42），把它永久存进账目行 = 把凭据长期留在另一张表里；
--   ③ 展示昵称 / 头像本来就该是「当时那一刻的样子」——与 venue_name（门店名快照，同表同判据）
--      同一语义：对方事后改名换头像，不应让你历史账目上的人凭空换了模样。
-- 故与 venue_name 同构：落账时快照一份，之后只读。
--
-- ── 存什么 / 不存什么（合规收敛点）──────────────────────────────────────────
-- 存：每位同行者 {昵称, 头像 URL, 关系(HOST=对方是出示二维码的人 / JOINER=对方扫码加入)}。
-- 不存：对方 userId（V45 的口径原样继承——不给跨会话 / 跨账目串联同一个人留通道）、
--       年龄 / 性别 / 城市（从不经计时分享通道下发）、对方的金额（账务隐私）。
-- 读：与整张表一致，全部接口 user-scoped，只有账目所有者本人读得到；管理端用量统计
--     （AdminSpendStatsService）不投影本列。
--
-- ── 列设计 ──────────────────────────────────────────────────────────────────
--   · companions_json varchar(4096) NULL：JSON 数组 [{"nickname":..,"avatarUrl":..,"relation":..}]；
--     NULL = 没有同行者（手动账目 / 单人计时 / V47 之前的存量行）。
--   · varchar 而非 TEXT / JSON：与 V42 rule_json 同款（Hibernate validate 对 varchar 映射无歧义，
--     长度护栏落在 SpendEntryLimits 单一声明处）。上限 6 人 × (昵称 64 + 头像 512 + 键名结构 ≈ 50)
--     ≈ 3.8K 字符；序列化后仍超 4096（引号转义膨胀的极端载荷）时服务端从尾部丢人直到放得下
--     ——**同行者是元数据，绝不让它拒掉一笔账**（SpendEntryLimits 的毒丸教训）。
--   · 写语义：请求不带 companions（老客户端 / 手动账目）= 保留库里已有值；带（含空数组）= 整体替换。
--     账目是 last-write-wins，但「老版本客户端重传同一条账」不应抹掉新版本写下的同行者。
--   · 无外键、不建索引（不按它查询）、不写 DB now()（全库约定）。
-- ============================================================================

ALTER TABLE qwt_spend_entries
    ADD COLUMN companions_json varchar(4096) NULL
        COMMENT '一同计时的人快照 [{"nickname":..,"avatarUrl":..,"relation":"HOST|JOINER"}]；NULL=无。仅账目所有者可读；不含对方 userId'
        AFTER duration_seconds;
