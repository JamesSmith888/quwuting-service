-- V29：门店「开业计划」字段（2026-09-17，方案见 docs/agents/50-venue-opening-plan.md）
--
-- 背景（根因，用户报障「南通寻梦缘歌舞厅明天开业，系统怎么填都别扭」）：
-- qwt_venues.status 只有 5 个**此刻事实**取值（OPEN / RENOVATING / CLOSED /
-- SUSPENDED / CEASED），没有「计划 / 预告」这一维。而「明天开业」是一条**将来时**
-- 信息——用一个现在时的字段去承载它，5 个取值里没有一个是它的位置：
--
--   · 直接置 OPEN  ⇒ 今天立刻是「营业中」，用户今天白跑（这正是 V25/48 号文档的
--     核心不变量要防的错判：人工置 OPEN 的代价 = 用户白跑一趟），且会给所有关注者
--     推一条「XX 恢复营业」的假通知，3 天人工锁的时间窗还与真实开业日错位；
--   · 保持停业    ⇒ 今天的事实正确，但「9月18日开业」这条信息**丢了**——用户看到
--     的是「已停业」（现在时）与活动行「门票减免 · 9月18日 起」（将来时）并存的
--     矛盾信号，两句都不含「明天开业」这个唯一重要的结论；
--   · 报「恢复营业」⇒ ReportType.RESUMED 的语义是「我此刻在场，看到它开门了」
--     （现在时、现场目击、承担解除暂停信号的角色），今天境内无目击者；且**不采纳
--     也不安全**——门店报告信号会上列表「最新上报」行与详情页公告条，它以
--     「恢复营业 · 舞友上报 · 未经核实」的形态照样曝光，假信息一样被消费。
--
-- ── 设计：把「计划」补成一维数据，而不是补第 6 个状态枚举值 ──────────────
--
--   status              —— 现在时的事实（5 态不动，一行不改）
--   expected_open_date  —— 将来时的计划（本列）
--
-- 展示层派生 UPCOMING（与既有 NOT_OPEN_YET「未到营业时间」**完全同构**：
-- 那是「日内将来时」——存储态 OPEN × 不在营业时段 → 「今晚 19:00 开门」；
-- 本列支撑「跨日将来时」——存储态停业 × 开业日未到 → 「9月18日开业」）。
-- 两者都在 utils/venueStatus.ts 单点收口，见 50 号文档。
--
-- 为什么走「派生 + 到点调度」，而不是新增 VenueStatus 枚举值：
--   ① 它是「日期 × 今天」的**函数**，不是独立事实。落库立刻会出现「9 月 19 日
--      库里还写着 UPCOMING」的假状态（同活动域 NOT_STARTED 由 ActivityStateResolver
--      派生而不落库的理由，见 49 号文档 §3）；
--   ② **所有基于存储态的守卫天然正确**：热度上报「非营业禁报」（27 号，status != OPEN
--      拦截）、报告类型守卫（RESUMED 仅对声称非营业门店有意义）、V25 的人工锁 /
--      豁免判定——全部只认 5 态，压根不知道 UPCOMING 存在，零改动。做成第 6 个枚举
--      则要审计全库每一处 status 判断，那才是真正的高风险改动；
--   ③ 到点的自动开业**必须真的写库**（否则徽标永远停在派生态、关注者通知发不出），
--      这个「计划兑现」的动作由调度器走 VenueService 正规通道完成，见 50 号 §3。
--
-- ── 与既有机制的关系（改前必读） ───────────────────────────────────────
--
-- V25 人工锁：调度器转 OPEN 后**打 3 天人工锁**（同人工置 OPEN 档位，走
--   lockOnManualChange）。理由——新店开业时舞讯大概率尚未收录它，次日「未上榜差集」
--   推断正好命中并把状态推回暂停；不打锁则「自动开业」第二天就自我推翻。48 号文档
--   已经把这条路径踩过一遍（这是人工意图的延伸，理应享受人工优先权）。
-- 状态日志：转换写 qwt_venue_status_logs，change_source = 'SCHEDULED'（新增值），
--   changed_by = NULL（系统自动，无操作人）；与 AGENT_BATCH / ADMIN 并列，
--   供管理端「更新记录」区分来源。
-- daily_sync_exempt：只声明「不参与舞讯推断」，**不阻止**开业计划的兑现（两件事
--   不同维度：豁免是「谁的话可信」，计划是「什么时候兑现」）。
--
-- 边界（明确不做）：
--   · 只做开业方向。对称的「X 日起停业改造」预告**暂不做**（2026-09-17 用户拍板），
--     但列设计留位——真要做时加 expected_close_date，展示层同构再加一个派生态。
--   · 不做历史回溯：存量门店全部 NULL（本就无计划，无需反推）。
--   · 不进离线快照（VenueSnapshotItem）：快照是「静态子集」，而本列**会自然过期**
--     ——离线端可能已过开业日却仍显示「9月18日开业」，比不带更坏。
--
-- 索引：调度器按 expected_open_date 扫（`<= today AND deleted = false`）。
-- 「即将开业」门店量级极小，普通索引足够；存量行全为 NULL（InnoDB 的 NULL 不进索引，
-- 故此索引近乎只覆盖真实有计划的那几行）。
-- 枚举/日期以原生类型存储（date ↔ LocalDate），禁 varchar（V13/V14 类型不匹配事故先例）。

ALTER TABLE qwt_venues
    ADD COLUMN expected_open_date date NULL COMMENT '预期开业日（将来时计划；到点由调度器自动转 OPEN 并清空。NULL = 无开业计划）',
    ADD INDEX qwt_idx_expected_open_date (expected_open_date);
