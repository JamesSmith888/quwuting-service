-- ── 隐私形态变更说明（原「坐标不出端」红线，经本迁移有意修订）──────────────
-- V33 原始红线 = 「用户经纬度在协议上不存在」，正当性来源 = 数据面最小化 +
-- 到访统计所需仅是距离。2026-10-08 用户裁决改为「主动同意 + 用途限定」形态：
--   · 采集门禁不变：仍只收「最新一条状态确立 = 用户显式开启」的 ping（V34 链路）；
--   · ⛔ 同意文案必须与事实同步（端侧首问 / 关闭挽留 / 设置页 / 足迹详情页四处
--     同批改动）——「不会保存您的具体位置」承诺自本版退役，替换为用途限定表述
--     （同源句：「位置仅用于门店统计，不对外展示」）；
--   · 用途限定 = admin 内部到访统计与轨迹分析；⛔ 不向 C 端 / 第三方展示；
--   · 仅**新记录**携带坐标（历史行恒 NULL，不可追溯补采）⇒ admin 展示必须显式
--     说明「另有 N 条无坐标」，⛔ 禁静默丢弃（「静默截断=谎报」同款纪律）。
