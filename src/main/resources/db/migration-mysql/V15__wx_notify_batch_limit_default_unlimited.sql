-- 微信通知突发档位默认值反转：3（默认）→ 0（不限）（2026-09-09，docs/agents/41）
--
-- 根因（为什么原默认值是错的）：V13 的默认档 3 防的是「用户同时收藏很多门店、
-- 批量状态变更同分钟轰炸」的假想场景；业务现实是用户不会同时收藏很多门店——
-- 防御机制让全体用户为低概率场景买单，且该参数曾以「通知上限」菜单项暴露给
-- 用户，把发送侧内部参数（我们一次最多打断用户几次）泄漏进了用户心智。
--
-- 决策（用户 2026-09-09 拍板）：
--   * 默认不限（0）：全部通知，任何收藏门店状态变化都发微信；
--   * 前端隐藏「通知上限」设置项：发送侧护栏降级为运维安全阀——字段与
--     POST /user/wx-subscribe-settings 接口保留（可按用户显式调档），仅无 UI；
--   * WxSubscribeBurstLimiter 不动：batchLimit=0 时自然跳过，零成本待命。
--
-- 回置口径：该功能从未上线（V13/V14 仅开发库执行，生产未部署），存量值 3 全部
-- 是「旧默认值」而非用户显式选择，统一回置 0；5 仅存在于开发库测试数据，
-- 生产无值，不做回置（保守，不覆盖任何可能的显式值）。
--
-- 铁律对齐：列类型维持 int（与实体 Integer 对齐，V14 教训），仅改 DEFAULT 与注释。

ALTER TABLE qwt_users
    MODIFY COLUMN wx_notify_batch_limit int NOT NULL DEFAULT 0 COMMENT '突发窗口内最多下发的微信通知条数（0=不限，默认/3=保守/5=重度；2026-09-09 起默认不限）';

UPDATE qwt_users SET wx_notify_batch_limit = 0 WHERE wx_notify_batch_limit = 3;
