-- V50（MySQL 轨道 = db/migration-mysql）: 门店到访「感谢」（致谢分享到店足迹的舞友）
--      （2026-10-13 用户拍板「按推荐方式实现」；文档 = docs/agents/52-venue-presence.md
--       「到访感谢」节；前端交互 = quwuting 仓 52 号；设计提案 =
--       quwuting-venue-visit-thanks-design-2026-10-06.md）
--
-- ⚠️ 编号说明：取号前已核对 db/migration-mysql 最大号 = V49；并行工作流会抢号，
--    部署前须再核对无第二份 V50（Flyway 对重复版本号直接拒启）。
--    PG 遗留轨道（db/migration）编号各自独立、勿混用。
--
-- ── 为什么要这张表（根因，不是"补一个点赞"）─────────────────────────────────
-- 1) 「感谢」文案早已对用户说出口：列表卡片到店足迹行 = 「感谢 N 位舞友 · N 次到过这
--    附近的足迹」——但产品里**没有任何让用户表达感谢的动作**，贡献者（允许采集的
--    舞友）也拿不到任何回音。「承诺与能力断裂」是本表要还的债（09 号文档同款判据）。
-- 2) 到访在数据模型里是**聚合量、不是事件**（一个 (user, venue, 15min桶) 的原始痕迹，
--    没有"某一次到访"这个可引用的实体）⇒ 必须先把「(门店, 到访用户)」这一对
--    **实体化**成可被感谢、可去重的对象，感谢才有挂载点。本表就是那个实体化。
--
-- ── 语义与红线 ──────────────────────────────────────────────────────────────
--   · 一行 = 「某位感谢者对某位贡献者在某门店的到访分享投了一次感谢」（三元组）。
--   · 幂等 = 全量唯一键 (venue_id, thank_user_id, target_user_id)：同一感谢者对同一
--     贡献者**永不发第二次**（无取消动作；重复点击由 ON DUPLICATE KEY 吸收）——
--     通知骚扰面天然有界（对齐 qwt_venue_crowd_report_likes 的「首次才通知」模式）。
--   · ⛔ 感谢数永不进任何算法（热度公式 / 到访项 / 可信度 / 列表角标）——与行级点赞
--     同款红线：可互刷的社交量一旦进算法必死；纯展示层精神激励、不产生积分。
--   · ⛔ 不引入新的身份暴露：被感谢者只收到一条匿名站内信（「N 位舞友」不点名）；
--     任何接口都不返回「谁到过这家店」的名单（52 号「永不公开」裁决）。
--   · 被感谢集合必须复用 VenuePresenceService#nearbyContributors（与卡片数字同一份
--     证据、同一窗口、同一排除集合）——⛔ 禁另算一套归因（否则"卡片说 6 人、
--     感谢只谢 4 人"的版本打脸会重演，52 号「展示口径一源」同款纪律）。
--
-- ── 隐私形态的守护（2026-10-08 V46 背景）────────────────────────────────────
-- 本表不改变到店足迹的采集门禁与用途限定（仍是「主动同意 + 门店统计」）；「被感谢」
-- 是对既有数据的**回馈交互**而非新的处理目的，但用户可感知事实新增了一条（会收到
-- 感谢信）⇒ 同意文案四处（首问 / 手动开启提醒 / 足迹详情页 / 运营公告）随本版同批
-- 补一句「您可能会收到其他舞友的感谢」，⛔ 禁只改代码不改告知。
--
-- ── 表：qwt_venue_visit_thanks ──────────────────────────────────────────────
--   · deleted 列走全库约定（无用户侧取消动作；软删语义留给未来管理端处置，YAGNI）。
--   · 时间列由 Java 传入（JVM = 北京时间，禁 DB now()——全库约定）。
--   · 无外键（全库约定）。
--   · 索引：
--       - 唯一键 (venue_id, thank_user_id, target_user_id)：幂等 + 「我已感谢过谁」查询前缀；
--       - qwt_idx_vvt_target (target_user_id, venue_id)：站内信合并正文的
--         「某用户在某店共收到几位感谢者」查询（COUNT DISTINCT 走它）。
--
-- ── 部署顺序 ────────────────────────────────────────────────────────────────
-- 后端先于小程序（纯增量：新表 + 新接口；旧客户端不知道该接口，行为零变化）。
-- ============================================================================

CREATE TABLE qwt_venue_visit_thanks (
    id             bigint      NOT NULL AUTO_INCREMENT,
    created_at     datetime(6) NOT NULL COMMENT '首次感谢时刻（JVM 北京时间）',
    updated_at     datetime(6) NOT NULL COMMENT '最近一次触发时刻（重复感谢不重发通知）',
    deleted        tinyint(1)  NOT NULL DEFAULT 0,
    venue_id       bigint      NOT NULL COMMENT '被感谢的到访所在门店（qwt_venues.id）',
    thank_user_id  bigint      NOT NULL COMMENT '感谢者（qwt_users.id，需登录）',
    target_user_id bigint      NOT NULL COMMENT '被感谢的到访贡献者（qwt_users.id；同对永不重复）',
    PRIMARY KEY (id),
    CONSTRAINT qwt_uk_vvt_venue_thank_target
        UNIQUE (venue_id, thank_user_id, target_user_id)
) COMMENT='门店到访感谢：一行=（感谢者, 贡献者, 门店）三元组；感谢数永不进算法、不产生积分';

-- 站内信合并正文「某用户在某店共收到几位感谢者」+ 未来「我收到的感谢」类查询
CREATE INDEX qwt_idx_vvt_target ON qwt_venue_visit_thanks (target_user_id, venue_id);
