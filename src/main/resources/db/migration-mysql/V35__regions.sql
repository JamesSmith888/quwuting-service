-- ============================================================================
-- V35（MySQL 轨道 = db/migration-mysql）: 行政区划名录（地名意图识别的权威真值）
--      （2026-09-30，搜索零结果「语义分诊」第二轮；前端权威文档 =
--       quwuting/docs/agents/35-venue-search.md「零结果空态：语义分诊」）
--
-- ── 为什么要有这张表（根因）─────────────────────────────────────────────
-- 用户报障：搜索框输入「合肥市」得到零结果，界面提示「换个关键词；如果知道这家店，
-- 告诉我们去收录」——把**城市未覆盖**说成了**这家店没收录**。第一轮（同日）引入
-- 「语义分诊」后，带行政区划后缀的词（市/区/县/州/盟/旗）能被识别，但**不带后缀的
-- 词（「合肥」「安徽」）仍然落到门店语义**——因为「合肥」与门店名同形，前端无从判断。
--
-- 结论：要判定「这个词是不是一个地名」，必须有行政区划真值；而真值
-- ① 不能放在前端（本仓既有约定：前端不维护任何城市名单，城市一律由后端下发，
--    见 miniprogram/services/city.ts）；
-- ② 不能从平台自有数据派生（qwt_venues 只有已收录的 108 个城市，舞讯采集表为空）；
-- ⇒ 由**后端单点持有**一份标准行政区划名录，经 GET /venues/regions 下发，前端缓存。
--
-- ── 数据与口径 ────────────────────────────────────────────────────────
--   · 数据源 = 民政部行政区划口径（省/地级/县级市三级），一次性灌入，属静态基础数据；
--   · **港澳台按「中国的一部分」口径补齐**（台湾省 / 香港特别行政区 / 澳门特别行政区）；
--   · 只取到「县级市」一层：平台 city 字段来自地图逆地理，实测含县级市
--     （仙桃/天门/潜江/兴义/盘州/喀什/阿克苏），补上这一层后
--     **已收录的 108 个城市 100% 命中本名录**（自洽性校验，见 docs）；
--   · 不收「县 / 市辖区 / 街道」：名字与门店名碰撞概率高，且用户以城市粒度找店。
--
-- ── 判据（消费方必须遵守）─────────────────────────────────────────────
--   · 本表只是「有哪些地名」的声明，**不参与任何筛选**（门店筛选仍走 qwt_venues.city）；
--   · 前端消费方式 = 精确等值 + 去后缀等值（「合肥」⇔「合肥市」），命中即用
--     **规范名**（带后缀）渲染文案；
--   · **降级方向有界**：名录未下发（后端未发版 / 离线）⇒ 回退到形态判据（带后缀才认），
--     即退回改动前的行为，不会把「我们不知道」说成「我们没有」。
-- ============================================================================

CREATE TABLE qwt_regions (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
    name VARCHAR(64) NOT NULL COMMENT '标准行政区划名（含后缀：省/市/自治区/特别行政区/自治州/地区/盟）',
    level VARCHAR(20) NOT NULL COMMENT 'PROVINCE=省级 / PREFECTURE=地级 / COUNTY_CITY=县级市',
    PRIMARY KEY (id),
    UNIQUE KEY uk_qwt_regions_name (name),
    KEY idx_qwt_regions_level (level)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='行政区划名录（地名意图识别的权威真值；静态基础数据，随民政部口径调整）';

