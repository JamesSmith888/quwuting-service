-- ============================================================================
-- V45: 计时「二维码同步给对方」——结算事实同步（2026-10-08）
--      （后端权威文档 = docs/agents/54-timer-share.md；前端 = quwuting 仓 docs/agents/59-timer-share.md）
--
-- ── 需求与模型（为什么加这四列）────────────────────────────────────────────
--
-- 业务：A、B 两人经二维码在同一服务端时间轴上各记各的账（V42 的「独立副本」）。
--       现实场景里两人一起跳、一起走——**谁先点了结算，另一个人理应能看到「对方几点结束」**，
--       并可以选择「按这个时间结束我这场」（建议而非强制：两人也可能各走各的）。
--       没有这四列时，另一方只能凭记忆回忆对方几点走的，账目会错。
--
-- 模型：结算 = 双方各自的一次「时间事实」上报（服务端时间轴的一刻 + 该端结算时的净时长），
--       **仍然不含金额**（金额由各端 `danceCost` 用各自规则的快照现算——各端规则可能不同，
--       且金额是账务隐私；V42 头注「服务端只存时间事实」的口径在这里原样继承）。
--
--   · 主持方一侧（本表 qwt_timer_shares）：host_settled_at_ms / host_settled_net_seconds
--   · 加入者一侧（qwt_timer_share_joins）：settled_at_ms / settled_net_seconds
--
-- ── 为什么不复用 closed_at_ms ───────────────────────────────────────────────
-- close 有三种触发（整场结算 / 单独结算 / 丢弃计时时的清理），**丢弃不产生结算事实**；
-- 且「关闭」是凭据生命周期（码失效），「结算」是账务事实（几点结束）——两件事各自独立。
-- 复用会让「丢弃」被误读成一次结算。故独立两列，语义单一。
--
-- ── 重新激活即结清（与 closed_at_ms 同口径）────────────────────────────────
-- 主持方「单独结算后撤销」会让同一场经 createOrRefresh 重新回到 ACTIVE
-- （V42 既有行为：status=ACTIVE + closed_at_ms=NULL）——此时 host 又回到计时中，
-- 「已结算」事实必须一并作废，故刷新路径同时清空 host_settled_at_ms / host_settled_net_seconds。
-- 加入者侧对称：撤销结算后重新结算 = 覆盖上报；撤销后未重新结算的残留事实如实保留
-- （概率低、影响小、重结算自然覆盖，见 54 号文档「已知边界」）。
--
-- ── 覆盖语义（幂等）────────────────────────────────────────────────────────
-- 重复上报 = 覆盖为最新一次（无「已结算不可改」约束——客户端重试与「撤销后重结算」
-- 都需要覆盖）。settle 接口故意**不检查会话状态**（CLOSED / EXPIRED 都可写）：
-- 结算恰恰大量发生在二维码 10 分钟有效期之后，这不是异常路径。
--
-- ── 时间列为什么仍是 bigint 毫秒 ────────────────────────────────────────────
-- 同 V42：参与「服务端时间轴」算术（对方端用往返校准把它换算回本机时间），
-- datetime 只会多一次时区换算。可读时间由 created_at / updated_at 提供。
-- ============================================================================

ALTER TABLE qwt_timer_shares
    ADD COLUMN host_settled_at_ms      bigint NULL COMMENT '主持方结算时刻（服务端时间轴 epoch ms）；NULL = 未结算',
    ADD COLUMN host_settled_net_seconds int   NULL COMMENT '主持方结算时这一场的净时长（秒）；NULL = 未结算';

ALTER TABLE qwt_timer_share_joins
    ADD COLUMN settled_at_ms       bigint NULL COMMENT '加入者结算时刻（服务端时间轴 epoch ms）；NULL = 未结算',
    ADD COLUMN settled_net_seconds int    NULL COMMENT '加入者结算时其计时的净时长（秒）；NULL = 未结算';
