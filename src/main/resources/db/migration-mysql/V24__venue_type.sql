-- ============================================================================
-- V24: 门店类型 venue_type（2026-09-13 用户拍板「私人歌友会」品类，
--      见 docs/agents/04-venue-domain.md「门店类型与地址可见性」）
--
-- 背景：平台此前只有「舞厅」一种门店，qwt_venues 无分类维度。现需录入一类
-- 新的经营性场所——私人歌友会（有门票、有舞伴费用、有营业时间，但地址刻意
-- 只公开到城市，用户想去须联系获取）。它与舞厅同属名录条目（都要能被搜到、
-- 都要展示消费与时间信息），却在「地址可见性」上根本不同，故需要显式品类维度。
--
-- 设计要点：
--  ① 类型派生地址可见性（而非另设开关）：歌友会 = 城市级地址，公开响应剥离
--     district / address / 经纬度；舞厅 / KTV = 完整地址 + 导航。新增类型时必须
--     在枚举里显式回答"它该不该藏地址"，编译期强制（见 VenueType 注释）。
--  ② 平台代发模型不变：门店创建接口恒 requireAdmin，本列不引入任何 UGC 写入面。
--  ③ 半径谓词对城市级类型放行（同批后端改动）：歌友会无坐标，若不放行会被
--     默认 300km 可达圈静默过滤——用户明确要求 300km 内永远包含歌友会。
--
-- 存量回填：ADD COLUMN 带 NOT NULL DEFAULT 'HALL'，MySQL 自动以默认值填充
-- 全部存量行（全量舞厅，语义正确），无需 UPDATE 回填——存量门店类型恒为舞厅。
-- 时间口径：本迁移只加列 + 索引，不写 created_at / updated_at 墙钟
-- （与既有「时间列由 Java 传」红线一致——无任何时间字段写入）。
-- 目录说明：本仓 MySQL 环境 Flyway 目录 = db/migration-mysql（全量基线，V1~V23），
-- 本迁移按该序列继续编号为 V24；db/migration 为遗留 Postgres 序列（勿复用）。
-- ============================================================================

ALTER TABLE qwt_venues ADD COLUMN venue_type varchar(20) NOT NULL DEFAULT 'HALL';

CREATE INDEX qwt_idx_venues_venue_type ON qwt_venues (venue_type);
