-- V40（MySQL 轨道 = db/migration-mysql）: 到访「被同址分摊」标记
--      （2026-10-06，文档 = docs/agents/52-venue-presence.md）
--
-- ⚠️ 编号说明：PG 遗留轨道（db/migration）与 MySQL 轨道编号各自独立、勿混用。
--    V39（次数列）已于 2026-10-06 15:45 落库 ⇒ 本迁移为增量ALTER。
--
-- ── 需求：同址分摊后，文案必须改口径（2026-10-06 用户裁决，方案 B）────────
--
-- 现网实证（2026-10-06 取证，13寻梦缘 / 14 抖舞 / 111 南来北往）：
--   · 三家坐标互相只差 20~40 米 ⇒ 同一同址组（group_size = 3）
--   · 寻梦缘自身只有 user 908；抖舞自身只有 user 65；停业的南来北往有 user 2、331
--   · 组内在营 2 家 ⇒ 每位用户按 1/2 分摊
--   · 小程序因此显示「感谢 2 位舞友」，而 admin 共享口径显示 3~4 人
--
-- **问题**：20m 的定位精度**根本无法分辨**到访者去的是哪家店。把分摊后的数字说成
-- 「这家店的舞友」，等于替系统断言了一个无法证实的事实（用户到店后发现无人去过 ⇒
-- 对整个功能失去信任）。分摊数字本身没错，错在**用词**——它表达的是"这附近"而非"这家店"。
--
-- ── 解法：把「是否被分摊」这一事实持久化，文案层据此换词 ────────────────────
--
--   · share = 1（本店独自吃下全部证据，或组内只有自己在营）⇒ 文案照旧
--     「感谢 N 位舞友 / N 次真实到店足迹」—— 事实无歧义。
--   · share < 1（证据被同址在营店分摊）⇒ 文案改**附近**语义
--     「感谢 N 位舞友 · N 次到店足迹」（去"真实"）+ 副行提示"到过这附近"。
--
-- ⛔ **不新增"附近人数"这类第二套数字**：那会让 admin 与小程序再多一处口径差。
--    本列只承载"是否被分摊"这个**布尔事实**，不承载任何新量。
--
-- ── 列设计 ──────────────────────────────────────────────────────────────────
--
--   · share_in_operation TINYINT(1) NOT NULL DEFAULT 1，1 = 未被分摊 / 0 = 被分摊。
--     用 TINYINT 而非 DECIMAL：本列**只表达二值**（是否被分摊），存具体小数会诱使
--     后人拿它做计算，而"分摊了多少"已由 visit_users_30d 的小数部分承载。
--   · 缺省 1 = 旧行/无分摊场景的天然取值（存量 9 行全部保持"未分摊"语义正确：
--     它们的 share 都 ≥ 1/k 且实际多为 1；refresh 每轮整表清零重写，存量值不依赖本列）。
--   · **不进公式**：它只是展示层的用词依据，热度仍读 visit_users_30d。
-- ============================================================================

ALTER TABLE qwt_venue_visit_metrics
    ADD COLUMN share_in_operation tinyint(1) NOT NULL DEFAULT 1
        COMMENT '同址分摊标记：1=未被分摊（文案可断言"到这家店"）/ 0=被同址在营店分摊（文案须改"附近"语义）。仅影响展示用词，不进公式'
        AFTER group_size;