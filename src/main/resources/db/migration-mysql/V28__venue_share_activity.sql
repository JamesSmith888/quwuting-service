-- ── V28：分享事件的活动维度（2026-09-16，docs/agents/49-venue-activities.md §8） ──
-- 根因：活动域（V27）落地后，活动**完全没有传播出口**。分享（`qwt_venue_shares`）是
-- 站内既有的增长主通道（能力启用 / 内容契约 / 归因闭环三层齐备，见 10 号文档），但它的
-- 粒度只到「场所」——分享卡片标题只拼「店名 · 城市区县 · 营业状态」，别人收到卡片
-- **看不出这家店今天有活动**。而活动恰好是站内最该被转发的内容：属地 + 时效 + 权益。
-- 修复：给分享事件补一个可选的活动维度，把归因从「谁分享的」升级为
-- 「**哪个活动被传播、带来多少人打开**」——这是活动独有的、可以拿去跟门店谈的数字。
--
-- 为什么是加列而不是新建一张活动分享表：
--   * 两类事件的语义、频控、软鉴权、上报时机（分享面板弹出即上报）与场所分享完全同构，
--     差别只是"这次分享的目标对象是谁"。新建表等于把 10 号文档整套契约复制一遍，
--     两份真值必然漂移（同 49 号"策略只给外层"的收敛理由）；
--   * 该表本来就是纯 append 的分析型事件日志，加一个 NULL 维度的代价是零。
--
-- 为什么可空：门店详情页 / 门店热度页的分享没有活动上下文（`activity_id` 恒 NULL）；
-- 只有"用户在看活动卡时点了分享"或"从活动分享卡片打开"才带值。
-- NULL = 场所级分享，与 V28 之前的历史行语义完全一致（**存量行不回填**，它们确实
-- 不知道当时有没有活动，替历史数据编一个归因是更坏的选择）。
--
-- 通道说明（两条事件共用本列，靠 event_type 区分）：
--   * SHARE 行 → 分享者点的是哪条活动的分享按钮（`options.target.dataset.actId`）
--   * OPEN 行  → 打开者的落地 URL 带了 `act_id`（分享路径透传），即"这条活动的分享
--                卡片被点开了"
-- 注意：本列**不是外键**（项目基线无 FK，与 venue_id 同风格）；活动即便后来被删除或
-- 到期下线，事件行仍保留原 activity_id——分析型数据不做级联清理。
--
-- 列类型 bigint 与实体 VenueShare.activityId（Long）对齐——铁律：新迁移列类型必须与
-- 实体字段 Java 类型匹配（V13/V14 的 tinyint×Integer 启动期事故先例）。
--
-- 索引 (activity_id, event_type) 服务管理端的**分组计数**（按活动聚合分享数 / 打开数），
-- 而不是单点查询——列表页一次 IN 查询取全部活动的两个计数，避免 N+1。

ALTER TABLE qwt_venue_shares
    ADD COLUMN activity_id bigint NULL
        COMMENT '活动 ID（V27 qwt_venue_activities）；NULL = 场所级分享，无活动上下文' AFTER venue_id,
    ADD INDEX qwt_idx_venue_shares_activity (activity_id, event_type);
