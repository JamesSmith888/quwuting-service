package org.quwuting.quwutingservice.config;

/**
 * 热度公式权重常量（**唯一事实源，2026-08-10 V2 权重收敛重构**）。
 * <p>
 * 根因（长期维护负担）：热度公式在<b>三处镜像</b>——VenueHeatService.computeHeat
 * （Java 常量）、VenueRepository.HEAT_SCORE（JPQL 排序片段）、VenueRepository
 * .findHotVenueIds（native SQL 热门判定）——历史上权重散落三处硬编码数字，
 * 调整权重漏同步一处即口径漂移（AGENTS.md「场所热度」明文约束）。
 * <p>
 * 收敛方案：全部非配置化权重收敛到本类常量，三处镜像经字符串拼接引用
 * （HEAT_SCORE（2026-08-27 拆出行为口径 HEAT_BEHAVIOR）/ findHotVenueIds 是 SQL 字符串，
 * 直接拼常量值）——一处定义、三处引用。积分权重是<b>运营可调参数</b>（V2 校准机制），
 * 不在此处，走 {@link PointsProperties#heatWeight()}（JPQL 参数 :pointsWeight 注入）。
 */
public final class VenueHeatWeights {

    private VenueHeatWeights() {}

    // ── 浏览贡献（2026-09-19 二重构：来源加权人次 + ln 压缩 → 去重人数口径） ──
    // 【为什么改】2026-08-27 为破马太闭环（排序→曝光→LIST 点入→浏览→排序）把浏览压成
    // ln(1+加权人次)，但压缩连"有多少人来看"一起压掉了——生产实证（2026-09-19 真库只读）：
    //   · 浏览贡献实测封顶 6.4 分（抖舞加权浏览 618，全网最高），而收藏 8 人 = 64 分；
    //   · UV 从 13 人 → 119 人（9 倍差距）在公式里只差 3.4 → 6.4 分；
    //   · 332 家门店「有人浏览、近30天 0 收藏」，其浏览贡献 2~5 分 < 1 次收藏（8 分）；
    //   · 收藏人数学实为 λ≈1 的泊松噪声（111 家有收藏的门店里 89 家恰好 1 人）。
    //   ⇒ 排序实际由最稀疏的信源主导，把区分度最大的信源压成了常数项。
    // 更根本的错配：09-19 已把收藏/评分/反馈改为「去重人数 × 线性」，浏览却仍是
    // 「加权人次 × ln」—— 量纲错配只修了一半。本轮把浏览也改为人数口径。
    //
    // 【为什么不能简单恢复线性 PV】PV 含两类真污染：① 匿名占 PV 的 45%~54% 且不可去重
    // （仅 60s 频控）；② PV/UV = 3.4~4.4，同一个人点开 4 次被当成 4 倍热度。故不是去掉
    // 压缩，而是**换压缩对象**：压的是"不可去重的匿名流量"，不是"有多少人来看"。
    //
    // 【新口径】浏览贡献 = 近30天去重浏览人数 × 0.30
    //                  + 近7天去重浏览人数 × 0.40
    //                  + ln(1 + 近30天匿名浏览行数) × 1.00
    //   ① 人数项：一人一天最多贡献 1（唯一键 (venue,user,date,source)），刷量无效；
    //      天花板由真实用户池决定（不会自催化无上限膨胀），无需再上 ln。
    //   ② 近7天独立一项：保留"热度要当下"的时效语义，且比旧 time_factor×2 更直白
    //      （旧做法把时效折叠进同一个加权和里，再被 ln 抹平，实际没生效）。
    //   ③ 匿名项：保住未登录用户的真实流量（占 PV 一半，丢弃则损失过半真实行为），
    //      但 ln 封顶 ≈6 分——刷 1000 次匿名行也只多 5 分，可刷面被压死。
    // 实测（生产真库）：头部店浏览项由 6.4 → 58 分，与收藏同量级；1 次收藏（8 分）不再
    // 能改变排序（需 ≈20 UV 才等效），排序抗扰动性显著提升。
    /** 浏览项：近30天<b>去重浏览人数</b>权重（登录用户，排除内部账号） */
    public static final double VIEW_UV_30D = 0.30;
    /** 浏览项：近7天<b>去重浏览人数</b>权重（时效项，与 30 天项叠加而非替代） */
    public static final double VIEW_UV_7D = 0.40;
    /** 浏览项：近30天匿名浏览行数的对数项权重（ln(1+匿名PV) × 本值，封顶 ≈6 分） */
    public static final double VIEW_ANON_LN = 1.00;

    /**
     * 收藏项权重（2026-09-01 口径收敛 + <b>2026-09-07 数值校准 15→8</b>）：热度公式收藏项
     * <b>唯一输入 = 近30天新增收藏</b>（取消收藏软删后自动抵消——一次收藏→取消 =
     * +8→−8 = 0，可对账）。收藏总数（favoriteCount）仅作页面展示（累计），不再参与热度公式。
     * 根因：09-01 旧口径「收藏总数×10 + 近30天新增×15」是集合包含关系（新增 ⊂ 总数），
     * 一次新收藏被重复计 10+15=25 分且存量永续让老店占优，已收敛为只计新增；
     * <b>09-07 数值再校准（西安火舞山音乐厅生产实证：1 次收藏即升至城市排名第 2）</b>——
     * 收藏是漏斗末端的「高意图主动信号」，但单次 15 分已超过任何门店整月浏览贡献的上限
     * （当时 ln(1+加权浏览) 现实封顶 ≈9）：收藏功能知晓率低 → 计数分母小、样本噪声大；
     * 「关注≠点收藏」用户的兴趣只体现在浏览/回访上，却被 ln 压缩到个位数——收藏单点
     * 主导排名 = 少数会用收藏按钮的用户替全量人气投票。×8 与单次评分（{@link #RATING}）
     * 同档：保留「主动信号 &gt; 浏览基座」的意图差，但不再一票碾压。
     * <b>2026-09-19 浏览改人数口径后本权重不变</b>：浏览项实测由封顶 6.4 升至 ≈58，
     * 单次收藏（8 分）已不再碾压整月浏览基座（需 ≈20 UV 才等效 8 分），量纲错配消除。论证见
     * docs/agents/05-venue-heat.md「收藏权重校准」。
     */
    public static final long NEW_FAVORITE = 8;

    /**
     * 运营权重（sortWeight）解锁阈值（2026-09-07 悬崖解锁修复）：列表排序 HEAT_SCORE
     * 的守卫壳从「行为热度 &gt; 0」上修为「行为热度 ≥ 本值」才叠加 sortWeight。
     * 根因：原二值开关在行为 0→单点信号（1 收藏 / 1 评分 = 8）时瞬间从 0 跳到全量
     * 运营权重，运营加权门店（历史种子店 30~50）被单个稀疏行为直接抬升登顶——
     * 与火舞山「1 收藏升至第 2」同根（见 {@link #NEW_FAVORITE}）。本值取 15 ≈
     * 2 次收藏（×8）或等价组合的量级：零行为门店与「恰好一个稀疏行为」的门店都不足以
     * 换取运营权重的曝光加码。只影响列表/推荐排序（唯一使用方 =
     * {@link org.quwuting.quwutingservice.venue.repository.VenueRepository#HEAT_SCORE}）；
     * 热门判定另有「行为热度 ≥ min-heat-score（70）」绝对门槛兜底，无需本守卫。
     */
    public static final long SORT_WEIGHT_GUARD_MIN_BEHAVIOR = 15;

    /**
     * 动态权重（2026-09-01 口径收敛）：由「动态总数」改为「近30天新增动态」。
     * 根因：动态是 admin 直发的运营内容而非用户行为，动态总数（存量、永不过期）让
     * 内容积累多年的老店靠存量压住新店；改窗口后运营活跃度信号保留、存量马太消除。
     */
    public static final long POST = 5;

    /** 近30天评分数权重 */
    public static final long RATING = 8;

    /** 近30天正向 Reaction 权重（仅 Polarity.POSITIVE；负向不计入公式） */
    public static final long REACTION = 3;

    /** 满意度偏移权重（(分-6)×20） */
    public static final long SATISFACTION = 20;

    /** 满意度中性基准（1-10 分制及格线）：高于 6 加分、低于 6 扣分 */
    public static final double SATISFACTION_NEUTRAL = 6.0;

    // ── 到访项（2026-10-06 V38 新增：到店足迹进排名） ────────────────────────────
    //
    // 【信号定位】到访是**唯一带物理成本**的信号（要出门、要到场），漏斗位置比收藏更深：
    //   曝光 → 浏览 → 按钮（收藏/评分/反馈）→ **到店** → 消费
    // 故「单票价值 ≥ 收藏（8）」；但它同时是全库**最稀疏**的信源。
    //
    // 【为什么不能裸加（生产实证，2026-10-06 只读模拟）】归因后 8 家有到访门店中
    // **5 家只有 1 个用户**（λ≈1 泊松，与 09-07「89 家收藏恰好 1 人」同类）。按收藏同档
    // 权重（人数×8）模拟的实测三条错误：
    //   · 西安「舞美时光酒吧」16 名 → 第 3 名（只因为 1 个人到过一次）；
    //   · 西安「钜之淋音乐酒吧」(CEASED) 57 → 21（W=15 时 → 第 5）；
    //   · 咸阳整城重排（全市 30 天仅 3 个浏览用户、门店热度全为 1，+8 即翻天）。
    // 根因：**固定权重的裸人数项 = 在热度越弱的地方给越多分**——南通头部
    // 172/138/59 加 8~15 分纹丝不动，西安头部 36/26/17 加 8 分就翻天。
    // ⇒ 这与 08-27 / 09-07 / 09-19 是同根事故，**不能靠"把权重调小"解决**。
    //
    // 【解法 = 免计基数】`max(0, 到访人数30d − VISIT_FREE_TIER)`：把"随曝光增长的那一层"
    // （恰好一个人路过的噪声）整体压掉，只保留"多个人真的来过"这层信息。
    // 依据：观测服从泊松，P(Poisson(1) ≥ 3) = 8% ⇒ 门槛取 3 时，「真实到访强度只有 1 人」
    // 的门店被误放行的概率只有 8%（门槛 4 为 1.9%，但会过度延迟生效，取 3）。
    // 形式取**连续线性**而非「n≥3 才计全量」——后者在 n=2→3 时产生 0→30 分的**悬崖**
    // （09-07 SORT_WEIGHT_GUARD_MIN_BEHAVIOR 同类教训）；max(0, n−2) 从门槛起连续：
    // 第 3 人 = 1W、第 4 人 = 2W，无跳变。
    //
    // 【实测影响（2026-10-06 生产真值 = 零位移）】过门槛的只有南通 3 家（丽莎 4 人 /
    // 抖舞 3 / 寻梦缘 3），且南通现有次序 1-2-3 不变；全网其他城市无一家过门槛
    // （西安/咸阳各店到访均 < 3）。⇒ 口径落定、影响延后：**当某城出现"30 天内 ≥3 个不同的
    // 人到过某店"时自动开始生效，无需再改代码**。
    //
    // 【取数形态】不是标量子查询直读 ping 表，而是读**物化汇总表**
    // qwt_venue_visit_metrics（V38，定时任务刷新）——归因（同址组 × 营业状态 × 用户并集）
    // 是 Java 侧计算，JPQL 无派生表能力；绕过归因直接写距离子查询会丢掉共享/让渡口径
    // （52 号 §1.1 第 1 条明文禁止）。**代价：到访项有刷新延迟**，与"当日行为当天反映
    // 排序"的现网契约不同——有意例外，见 docs/agents/05-venue-heat.md。
    //
    // 【永不做折减】不加"无到访 ⇒ 降权/门槛"：抗刷要求无到访降权，发现新店要求无到访
    // 不降权，在"到访"这一维度上不可调和（09-29 裁决）。**只做加性**。

    /**
     * 到访项权重（每"有效到访人数"的分值）。
     * <p>
     * = 10，略高于收藏（{@link #NEW_FAVORITE} = 8）：到访漏斗更深（带物理成本）故单票应更重；
     * 但它计的是**免计基数之上的边际票**（首票的信息量被 {@link #VISIT_FREE_TIER} 吸收），
     * 边际票信息量低于首票，故只取 1.25×收藏。<b>禁用 15 以上</b>——那会让单店到访在
     * 热度弱的城市碾压整城（见上方实证）。
     */
    public static final long VISIT = 10;

    /**
     * 到访项免计基数（人）：前 N 位到访者不计分，第 N+1 位起每人 {@link #VISIT} 分。
     * <p>
     * = 2（即"30 天内 ≥3 个不同的人到过"才开始计分）。依据 = 观测服从泊松、
     * {@code P(Poisson(1) ≥ 3) = 8%}（见上方「解法 = 免计基数」）。
     * <p>
     * <b>本常量同时是展示门槛的来源</b>：列表页到访胶囊只在
     * {@code 到访人数 ≥ VISIT_FREE_TIER + 1} 时下发 ⇒ 卡片上出现的数字**必然对应正分**，
     * 不会出现"显示了人数却不加分"的隐性矛盾。
     */
    public static final long VISIT_FREE_TIER = 2;
}
