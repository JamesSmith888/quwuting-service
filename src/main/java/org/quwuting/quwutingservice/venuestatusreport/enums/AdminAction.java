package org.quwuting.quwutingservice.venuestatusreport.enums;

/**
 * 管理端处置标记（2026-08-11 新增，区分"已采纳"与"已移除"两种 soft delete 语义；
 * 2026-08-28 扩展 KEPT 第三级——存疑保留）。
 * <p>
 * 旧实现采纳与移除同为 {@code deleted=true}，公开视图无法区分"已核实"与"已清理"。
 * 紧急公告区需要展示"已核实"（采纳后公告保留至 TTL 过期，带核实标记），而移除的
 * 信号立即从公开视图消失——故引入本列区分两种处置。null = 未处置（活跃信号）。
 * <p>
 * 处置三分级（2026-08-28 定稿，与置信度分层同哲学——权威性决定状态语义，置信度
 * 决定视觉权重）：
 * <ul>
 *   <li>{@link #ADOPTED} 采纳 = 平台背书"已核实"（联动营业状态 + 奖励 + 站内信）；</li>
 *   <li>{@link #KEPT} 保留 = 平台不背书但信号继续公示（无法核实但非恶意，不联动
 *       营业状态、不发分，公告区以中性"未经核实"展示至 TTL 自然过期）；</li>
 *   <li>{@link #REMOVED} 移除 = 平台否定（恶意/虚假信号清理，公开视图即时消失，
 *       管理端"已处理"历史保留审计留痕）。</li>
 * </ul>
 * 用户重新上报（upsert 恢复软删记录）时本列重置为 null。
 */
public enum AdminAction {
    /** 已采纳：管理员核实属实（公告区保留展示至 TTL 过期，带"已核实"标记） */
    ADOPTED,
    /** 已保留：无法核实但非恶意（公告区继续公示至 TTL 过期，中性展示，不联动营业状态） */
    KEPT,
    /** 已移除：平台清理恶意/虚假信号（公开视图即时消失，管理端历史保留） */
    REMOVED
}
