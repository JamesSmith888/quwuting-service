package org.quwuting.quwutingservice.venue.change;

/**
 * 门店「事实」变更的类别（2026-10-01，门店读模型失效收敛，见 docs/agents/29-performance.md
 * 「门店读模型失效：领域事件」）。
 * <p>
 * <b>只用于审计与日志可读性，不参与失效决策</b>：任何门店事实变化一律让<b>全部</b>门店读模型
 * 失效（逐店：实体 / 详情公共部分 / 热度；全局：列表 / 城市分面 / 热门集合 / 城市统计）。
 * 刻意不按类别挑选子集——历史上每条写路径各自决定「该失效哪几个缓存」，恰恰是漏失效的
 * 根因（舞讯批量写库漏逐出实体缓存、别名/活动写路径漏失效列表缓存等，见 29 号文档）。
 * 门店事实写入频率低（人工编辑 + 每日批量），全量失效的成本可以忽略。
 * <p>
 * 与「行为信号」严格区分：收藏 / 浏览 / 表情 / 评分 / 动态 / 积分等**用户行为**只影响热度
 * 输入，由各自写路径调用 {@code VenueHeatService#invalidate}，不发本事件（它们不改变门店
 * 本身的事实，列表排序靠 60s TTL 兜底即可）。
 */
public enum VenueFactChange {

    /** 新建门店（单条 / 批量建档） */
    CREATED,

    /** 门店资料编辑（名称/地址/营业时段/票价/标签/类型/开业计划/封面等整表字段） */
    PROFILE,

    /** 营业状态变更（人工直改 / 舞讯批量 / 上报采纳 / 开业计划兑现） */
    STATUS,

    /** 坐标变更（批量地理编码回填） */
    LOCATION,

    /** 公开相册 / 封面图变更 */
    PHOTO,

    /** 用户可见别名增删（KW_MATCH 结果集载体） */
    ALIAS,

    /** 营业活动发布 / 编辑 / 下线 / 到期（「有活动」筛选载体） */
    ACTIVITY,

    /** 认领关系变更（claimedBy） */
    CLAIM,

    /** 舞讯同步所有权字段变更（人工锁解除 / 永久豁免） */
    SYNC_GUARD
}
