package org.quwuting.quwutingservice.venuepresence.enums;

/**
 * 同址门店的到访归因方式（2026-10-03，52 号 §4.2 同址组 + §4.4 营业状态消歧）。
 * <p>
 * 背景：同楼的门店经地址级地理编码后坐标重合或只差数十米，手机定位在物理上分不出用户在哪一家。到访证据是
 * 「有人在这个位置」，归属哪家由<b>位置之外</b>的事实决定——第一层用的是门店营业状态：
 * 长期不在营的店（装修 / 暂停 / 停业）不可能被到访，同址只剩一家在营时证据归它。
 * <p>
 * 状态全集（每家店恰好一种，服务端判定、admin 原样展示，禁前端二次推导）：
 */
public enum CoLocatedAttribution {

    /** 无同址门店：只算本店上的证据 */
    NONE,

    /**
     * 共享：本店与同址的其他在营门店分不出彼此（或全组都不在营、无从归属）——
     * 数字是「这个位置」的到访，组内各店同数，<b>不可相加</b>
     */
    SHARED,

    /** 并入：本店是同址唯一在营的门店，同址不在营门店上的证据并入本店（如丽莎 ← 暂停营业的一壶淡泊） */
    ABSORBED,

    /** 让渡：本店当前不在营且同址有在营门店，该位置的证据归在营门店，本店计 0 */
    YIELDED
}
