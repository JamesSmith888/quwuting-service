package org.quwuting.quwutingservice.user.dto.response;

/**
 * 用户「最常去的那家门店」——管理端辨认匿名用户的<b>描述性身份</b>（2026-09-29；
 * 仅 ADMIN 消费，随 {@link AdminUserItem} / {@link AdminUserDetailResponse} 下发）。
 * <p>
 * <b>为什么需要它</b>：平台 98% 的用户从未改过昵称（生产实测 872 个存活用户里 857
 * 个昵称仍是默认值「微信用户」），管理端列表一行行「微信用户」没有任何辨认力。
 * 而用户的行为天然指向具体门店——「常去 XX 舞厅的那个人」是运营真正能记住、
 * 能在沟通中指代的描述。它是<b>内部辨认手段</b>，不是用户资料，不下发到小程序端。
 * <p>
 * <b>口径（单一定义，见 {@code AdminUserStatsService#topVenuesFor}）</b>：
 * 窗口 = 近 90 天；事件 = 行为目录里 {@code RefKind.VENUE} 的全部事件（门店维度的
 * 浏览/分享/表情/收藏/关注/热度上报/信息上报/标注/认领，各档位都算——辨认要的是
 * 「他对哪家店有过动作」，不是「他算不算活跃」）；取该用户动作次数最多的那家。
 * <p>
 * <b>为什么低于阈值的用户返回 null 而不是返回次数 1 的门店</b>：只去过一次不构成
 * 「常去」，把偶然一次渲染成身份标签是误导（运营会据此错误归类）。阈值由后端判，
 * 前端收到 null 即不渲染——<b>口径不留一份在前端</b>。
 * <p>
 * <b>合规</b>：只下发门店名与城市（门店是平台公开黄页数据），<b>不含</b>用户坐标、
 * 不含 openId；门店已软删则该项整体为 null（不拿已下架门店当身份标签）。
 */
public record TopVenue(
        /** 门店 id（null = 无；前端可据此跳门店详情） */
        Long venueId,
        /** 门店名 */
        String name,
        /** 门店所在城市（跨城同名门店的消歧依据，前端展示可选） */
        String city,
        /** 窗口内该用户对该门店的动作次数（≥ 阈值才产生本记录） */
        long count
) {}
