package org.quwuting.quwutingservice.message.enums;

/**
 * 站内信类型（通用消息中心的消息分类，见 AGENTS.md「站内信（消息中心）」）。
 * <p>
 * 新增消息类型 = 在此追加枚举值 + 同步前端 {@code types/message.ts} 的联合类型
 * 与展示文案（code 即唯一标识，前端按 code 渲染图标/文案，禁止前后端各自拼串）。
 */
public enum MessageType {
    /** 舞伴主页审核结果（通过/驳回，驳回附原因） */
    DANCER_REVIEW,
    /** 舞伴主页管理状态变更（隐藏/恢复展示） */
    DANCER_STATUS,
    /**
     * 上报处理结果（2026-08-10 新增，见 AGENTS.md「统一用户上报 → 处理结果站内信」）：
     * 管理端对用户上报（venuefeedback）的实际流转（采纳/采纳不奖励/已处理/忽略）完成时
     * 发送给上报者，同事务、幂等（仅 PENDING→终态实际流转时发一次）；匿名上报不通知。
     * 软关联 VENUE（深链场所详情页）。
     */
    FEEDBACK_RESULT,
    /**
     * 暂停营业报告处理结果（2026-08-10 新增）：管理端采纳暂停报（核实属实并标记门店
     * SUSPENDED + 发积分）时发送给上报者，同事务、幂等（仅活跃→已采纳实际流转时发一次）；
     * 匿名上报不通知。移除（虚假信号）不通知上报者（与用户自撤同语义，见 AGENTS.md
     * 「场所状态上报 · 管理端处置」）。软关联 VENUE（深链场所详情页）。
     */
    STATUS_REPORT_RESULT,
    /**
     * 关注门店营业状态变化（2026-08-12 新增，见 AGENTS.md「关注门店营业状态通知」）：
     * 门店营业状态实际变更（updateVenue / 采纳暂停/恢复报告）时发送给该店关注者
     * （qwt_venue_status_watchers），同事务、幂等（一次状态变更一条消息）。
     * 驱动首页「关注状态变化」提醒卡片（未读即提醒，点击深链门店详情页 + 标记已读）。
     * 软关联 VENUE（深链场所详情页）。
     */
    VENUE_STATUS_CHANGED,
    /**
     * 舞伴信息核验结果（2026-08-14 新增，见 AGENTS.md「舞伴官方认证」）：
     * 管理员授予/撤销「信息已核验」标识时发送给舞伴创建人，同事务、幂等（仅实际
     * 状态变迁发一次）；撤销必附原因（延续"被指涉方有申辩权"——被撤销舞伴可查原因）。
     * 软关联 DANCER（深链舞伴详情页）。
     */
    DANCER_VERIFICATION,
    /**
     * 邀约状态变化（2026-08-26 新增，22 号文档「邀约中转」）：管理员发放/拒绝、
     * 24h 自动降级（AUTO_RELEASED/EXPIRED）<b>实际流转时</b>同事务发送给客人——
     * 客人提交邀约后「马上能收到消息」（驱动 me 页「消息」入口 + tabBar 未读徽标，
     * 点击直达邀约详情），无需主动刷新「我的邀约」。
     * 内容 = DemandStatus.statusText 服务端权威友好文案（尊重友好原则，前端零拼接）；
     * 幂等 = 仅 updateStatusIfPending 实际流转（PENDING → 目标态）时发一次。
     * 软关联 DEMAND（深链邀约详情页 pages/demand-detail?id=）。
     */
    DEMAND_STATUS,
    /**
     * 意见反馈处理结果（2026-08-28 新增，平台级意见反馈）：管理端对
     * qwt_app_feedbacks 的实际流转（采纳/采纳不奖励/已处理/忽略）完成时发送给
     * 反馈者，同事务、幂等（仅 PENDING→终态实际流转时发一次）；匿名反馈不通知。
     * 与 FEEDBACK_RESULT（门店维度上报）独立成类，标题/内容/深链目标不同。
     * 软关联 APP_FEEDBACK（深链意见反馈页「我的反馈」列表）。
     */
    APP_FEEDBACK_RESULT,
    /**
     * 今晚热度确认（2026-09-03 新增，docs/agents/27-venue-crowd-report.md「确认后
     * 积分」闭环）：上报被 ≥3 位舞友确认（众包互认）时发送给<b>被确认的上报者</b>
     * （不含本次提交触发者——其提交响应已即时告知），同事务、每行上报至多发一次
     * （与 CROWD_CONFIRMED 积分发放同源幂等）。软关联 VENUE（深链门店详情页）。
     * 反向通知（收藏者看到收藏门店热度被确认）复用本类型，标题/内容区分口径。
     */
    CROWD_CONFIRMED
}
