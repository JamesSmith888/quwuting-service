package org.quwuting.quwutingservice.announcement.enums;

/**
 * 公告触达等级（2026-09-15 建立，docs/agents/34-announcements.md「触达等级」节）。
 * <p>
 * <b>它回答的问题</b>：这条公告<b>是否构成用户的未读债务</b>——即"用户不知道它就会吃亏"
 * 的那种信息。它与另外两个维度正交、互不替代：
 * <ul>
 *   <li>{@code category} = 内容<b>分类</b>（列表上给用户看的标签）；</li>
 *   <li>{@code pinned} = <b>位置</b>（是否进首页公告栏这个强触达位）；</li>
 *   <li>{@code touchLevel} = <b>打扰与否</b>（是否计入未读徽标 / 未读红点）。</li>
 * </ul>
 * <p>
 * <b>位置口径与打扰口径的关系（2026-10-08 当日两次修订，以当日 16:57 用户拍板为准）</b>：
 * 上午版曾把两口径「同源」——值得打扰（ALERT）才配占据首页位，SILENT 档在 Service 侧被
 * 显式拒绝置顶；当日 16:57 用户拍板「<b>舞讯依旧要顶置，以我为准</b>」⇒ <b>两口径解耦</b>：
 * 任一触达档（含 SILENT 的每日舞讯）均可被<b>显式置顶</b>——位置是运营 / 发布链路的显式决策，
 * 档位只回答「是否计入未读」这一个问题。容量为 1 的稀缺性不变量不变，由
 * {@code HomeSlotService}（claim / 显式拒绝）+ V44 唯一索引保证。
 * <p>
 * 历史回溯（教训保留）：位置口径曾被写死在每日舞讯 Skill 的固定模板里（{@code pinned=true}）
 * 且无容量约束 —— 36 条公告可同时置顶、读端静默取第一条 ⇒「置顶动作系统性不兑现」。
 * 「容量=1 + 显式拒绝不自动抢占」这半边修复继续有效。
 * 判据写在枚举里（而非散在 Service 的 if 里）是为了让它与 {@link
 * AnnouncementCategory#defaultTouchLevel()} 一样<b>可单测、可读、只有一个声明处</b>。
 *
 * <p>
 * <b>根因背景（为什么要有这个字段）</b>：公告域原本的未读口径是"全部可见公告 − 已读回执"
 * （每一条都算未读、且必须逐条进详情消除）。该模型成立的前提是"公告 = 低频运营内容，
 * 每条都值得读"——这是 2026-09-01 设计时的真实业务形态。但 2026-09-09「公告分开制」
 * （同日可并存多条 DATA_UPDATE）与 2026-09-15「高置信永远自动发公告」之后，公告变成
 * <b>日更高频流水</b>（每日舞讯），前提被打破而未读模型没有随之演进 ⇒ 徽标只增不减、
 * 用户被迫逐条点击、最终对徽标脱敏（"狼来了"）。修复不是给某类公告打特例补丁，而是
 * 把"要不要打扰用户"这件事<b>显式建模</b>，让未读口径有一个可读、可审、可扩展的唯一判据。
 * <p>
 * <b>判据（新增公告时怎么选）</b>：问一句"用户若没看到它，会不会吃亏？"
 * <ul>
 *   <li>{@link #ALERT} —— 会（新功能上线、规则调整、平台停机等需要用户知晓的变更）：
 *       计入未读徽标与未读红点；</li>
 *   <li>{@link #SILENT} —— 不会（数据更新 / 每日舞讯等流水记录、可查即可的内容）：
 *       照常出现在公告中心列表、可搜索可阅读，不产生任何未读计数。</li>
 * </ul>
 * （位置的置顶与否与档位无关——见上方「位置口径与打扰口径的关系」。）
 * 默认档由 {@link AnnouncementCategory#defaultTouchLevel()} 单点派生（禁在调用方散落 if/else）。
 */
public enum AnnouncementTouchLevel {

    /** 需用户知晓：计入未读徽标 / 未读红点，未读即"用户欠一个知道"。 */
    ALERT,

    /** 不打扰：仅在公告中心可查，恒不计入未读。 */
    SILENT;

    /**
     * 是否有资格占据首页公告位（<b>位置口径的判据单点</b>，2026-10-08）。
     *
     * <p><b>当前语义 = 全档放行</b>：任一触达档（含 SILENT 的每日舞讯）均可被显式置顶——
     * 2026-10-08 16:57 用户拍板「<b>舞讯依旧要顶置，以我为准</b>」，位置口径与打扰口径解耦。
     * 位置从此是运营 / 发布链路的<b>显式决策</b>：想要置顶就显式给 {@code pinned=true}，
     * 档位只回答"是否计入未读"这一个问题。
     *
     * <p><b>为什么保留这个"恒放行"的方法而不删除</b>：判据单点的结构价值——首页位的
     * "资格判据"与"容量校验"是两件事（后者在 {@code HomeSlotService#assertClaimable}
     * 冲突显式拒绝 + V44 唯一索引兜底）；将来若再需要按档位限制占位（或引入新档位），
     * 改这一处即可，消费方（{@code AnnouncementService#resolvePinned} 与管理端镜像）无需再改。
     *
     * <p><b>沿革</b>：本方法当日两版——上午版 {@code return this != SILENT}（SILENT 档禁止
     * 占位，Service 侧显式拒绝置顶）；16:57 用户拍板后翻转为全档放行（本条）。
     */
    public boolean eligibleForHomeSlot() {
        // 2026-10-08 16:57 用户拍板「舞讯依旧要顶置，以我为准」：位置与打扰解耦，全档放行。
        // （上午版为 `return this != SILENT`——SILENT 档在 Service 侧被显式拒绝置顶；已作废。）
        return true;
    }
}
